"""Generate the culture-merging files for the "Pop Cultures" game rule.

Usage (from the repository root):
    python tools/gen_culture_merge.py

Input: tools/vl_culture_data.json, extracted from the vanilla game files (00_cultures.txt,
discrimination_traits, localization). Regenerate it after a game patch that changes cultures.

Each heritage and each heritage group merges into one existing vanilla culture (its
representative), so content written for that culture keeps working. The representative's
on-screen name follows the game rule through customizable localization.
"""
import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = json.load(open(os.path.join(ROOT, "tools", "vl_culture_data.json"), encoding="utf-8"))
CULTURES = DATA["cultures"]
NAMES = DATA["names"]

# Representative per heritage group (chosen for the most country content in that group).
GROUP_REPS = {
    "heritage_group_european": "french",
    "heritage_group_east_asian": "han",
    "heritage_group_middle_eastern": "turkish",
    "heritage_group_african": "swahili",
    "heritage_group_south_asian": "bengali",
    "heritage_group_southeast_asian": "vietnamese",
    "heritage_group_north_asian": "manchu",
    "heritage_group_central_asian": "kazak",
    "heritage_group_indigenous_american": "cherokee",
    "heritage_group_indigenous_oceanic": "hawaiian",
    "heritage_group_promethean": "promethean",
}

# Heritage representatives that differ from the automatic choice.
HERITAGE_OVERRIDES = {
    "heritage_germanic": "north_german",
    "heritage_east_slavic": "russian",
    "heritage_north_american_settler": "yankee",
    "heritage_south_slavic": "serb",
    "heritage_nordic": "swedish",
    "heritage_iberian": "spanish",
    "heritage_netherlandish": "dutch",
    "heritage_deccani": "marathi",
}


def heritage_reps():
    by_heritage = defaultdict(list)
    for culture, info in CULTURES.items():
        by_heritage[info["heritage"]].append(culture)
    reps = {}
    for heritage, cultures in by_heritage.items():
        if heritage in HERITAGE_OVERRIDES:
            reps[heritage] = HERITAGE_OVERRIDES[heritage]
            continue
        same_name = heritage.replace("heritage_", "")
        if same_name in cultures:
            reps[heritage] = same_name
            continue
        reps[heritage] = sorted(cultures, key=lambda c: (-CULTURES[c]["refs"], c))[0]
    return reps


def chain(pairs, test, action):
    out = []
    for i, (trait, target) in enumerate(pairs):
        kw = "if" if i == 0 else "else_if"
        out.append(f"    {kw} = {{\n        limit = {{ {test(trait)} }}\n        {action(target)}\n    }}")
    return "\n".join(out)


def country_effect(name, pairs, has):
    body = []
    for i, (trait, target) in enumerate(pairs):
        kw = "if" if i == 0 else "else_if"
        body.append(f"        {kw} = {{\n            limit = {{ {has} = {trait} }}\n"
                    f"            cu:{target} = {{ save_scope_as = vl_new_culture }}\n        }}")
    return (f"{name} = {{\n    save_scope_as = vl_country\n    every_primary_culture = {{\n"
            f"        save_scope_as = vl_old_culture\n" + "\n".join(body) + "\n"
            "        scope:vl_country = { add_primary_culture = scope:vl_new_culture }\n"
            "        if = {\n            limit = { NOT = { this = scope:vl_new_culture } }\n"
            "            scope:vl_country = { remove_primary_culture = scope:vl_old_culture }\n        }\n"
            "    }\n}\n")


def homeland_effect(name, mapping):
    lines = [f"{name} = {{"]
    for culture in sorted(mapping):
        rep = mapping[culture]
        if rep != culture:
            lines.append(f"    every_state_region = {{ limit = {{ is_homeland = cu:{culture} }} add_homeland = cu:{rep} }}")
    lines.append("}\n")
    return "\n".join(lines)


def main():
    h_reps = heritage_reps()
    for group, rep in GROUP_REPS.items():
        assert CULTURES[rep]["group"] == group, (group, rep)
    for heritage, rep in h_reps.items():
        assert CULTURES[rep]["heritage"] == heritage, (heritage, rep)

    group_pairs = sorted(GROUP_REPS.items())
    heritage_pairs = sorted(h_reps.items())
    culture_to_group_rep = {c: GROUP_REPS[i["group"]] for c, i in CULTURES.items()}
    culture_to_heritage_rep = {c: h_reps[i["heritage"]] for c, i in CULTURES.items()}

    header = ("# Victoria 3 Lite: culture merging used by the \"Pop Cultures\" game rule.\n"
              "# GENERATED by tools/gen_culture_merge.py. Edit the generator, not this file.\n\n")
    pop_action = lambda t: f"change_pop_culture = {{ target = cu:{t} value = 1 }}"
    effects = header
    effects += "vl_pop_culture_to_group_effect = {\n" + chain(
        group_pairs, lambda g: f"culture = {{ has_discrimination_trait_group = {g} }}", pop_action) + "\n}\n\n"
    effects += "vl_pop_culture_to_heritage_effect = {\n" + chain(
        heritage_pairs, lambda h: f"culture = {{ has_discrimination_trait = {h} }}", pop_action) + "\n}\n\n"
    effects += country_effect("vl_country_cultures_to_group_effect", group_pairs, "has_discrimination_trait_group") + "\n"
    effects += country_effect("vl_country_cultures_to_heritage_effect", heritage_pairs, "has_discrimination_trait") + "\n"
    effects += "# Representatives inherit the homelands of every culture merged into them.\n"
    effects += homeland_effect("vl_homelands_to_group_effect", culture_to_group_rep) + "\n"
    effects += homeland_effect("vl_homelands_to_heritage_effect", culture_to_heritage_rep)
    write("common/scripted_effects/vl_culture_effects.txt", effects)

    # Customizable localization: name each representative by its group or heritage under the rule.
    group_of_rep = {rep: g for g, rep in GROUP_REPS.items()}
    heritage_of_rep = {rep: h for h, rep in h_reps.items()}
    reps = sorted(set(group_of_rep) | set(heritage_of_rep))
    cl = ("# Victoria 3 Lite: culture names that follow the \"Pop Cultures\" game rule.\n"
          "# GENERATED by tools/gen_culture_merge.py.\n")
    names = "l_english:\n"
    orig = ""
    for rep in reps:
        cl += f"\nvl_cname_{rep} = {{\n    type = country\n"
        if rep in group_of_rep:
            cl += f"    text = {{\n        trigger = {{ has_game_rule = vl_culture_groups }}\n        localization_key = {group_of_rep[rep]}\n    }}\n"
        if rep in heritage_of_rep:
            cl += f"    text = {{\n        trigger = {{ has_game_rule = vl_culture_heritages }}\n        localization_key = {heritage_of_rep[rep]}\n    }}\n"
        cl += f"    text = {{\n        localization_key = vl_cname_orig_{rep}\n    }}\n}}\n"
        names += f" {rep}:0 \"[GetPlayer.GetCustom('vl_cname_{rep}')]\"\n"
        orig += f" vl_cname_orig_{rep}:0 \"{CULTURES[rep]['name']}\"\n"
    write("common/customizable_localization/vl_culture_names.txt", cl)
    write("localization/replace/english/vl_culture_names_l_english.yml", names)
    write("localization/english/vl_culture_names_orig_l_english.yml", "l_english:\n" + orig)

    # A readable table of what merges into what.
    md = ["# Culture merging (generated)", "",
          "| Group | Group culture | Heritage | Heritage culture | Merged cultures |", "|---|---|---|---|---|"]
    by_h = defaultdict(list)
    for c, i in CULTURES.items():
        by_h[i["heritage"]].append(c)
    for h in sorted(h_reps, key=lambda h: (CULTURES[h_reps[h]]["group"], h)):
        g = CULTURES[h_reps[h]]["group"]
        md.append(f"| {NAMES.get(g) or g} | {GROUP_REPS[g]} | {NAMES.get(h) or h} | {h_reps[h]} | {', '.join(sorted(by_h[h]))} |")
    write("docs/culture_merging.md", "\n".join(md) + "\n", bom=False)
    print(f"{len(GROUP_REPS)} groups, {len(h_reps)} heritages, {len(reps)} renamed cultures")


def write(rel, text, bom=True):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8-sig" if bom else "utf-8", newline="\n") as f:
        f.write(text)


if __name__ == "__main__":
    main()
